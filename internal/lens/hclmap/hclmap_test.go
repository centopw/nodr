type testResource struct {
	Name    string     `hcl:"name"`
	Size    int        `hcl:"size"`
	Enabled *bool      `hcl:"enabled,optional"`
	Note    string     `hcl:"note,optional"`
	Tags    []string   `hcl:"tags,set,optional"`
	CPU     *testCPU   `hcl:"cpu,block"`
	Agent   *testAgent `hcl:"agent,block,optional"`
	Disks   []testDisk `hcl:"disk,block"`
}

type testCPU struct {
	Cores int    `hcl:"cores"`
	Type  string `hcl:"type,optional"`
}

type testAgent struct {
	Enabled bool `hcl:"enabled"`
}

type testDisk struct {
	Size    int    `hcl:"size"`
	Storage string `hcl:"storage"`
	SSD     bool   `hcl:"ssd,optional"`
}

var target = Target{Type: "resource", Labels: []string{"example_vm", "web"}}

func boolPtr(b bool) *bool { return &b }

func sample() testResource {
	return testResource{
		Name:    "web",
		Size:    4096,
		Enabled: boolPtr(true),
		Tags:    []string{"a", "b"},
		CPU:     &testCPU{Cores: 2, Type: "host"},
		Disks:   []testDisk{{Size: 32, Storage: "local"}, {Size: 64, Storage: "ceph", SSD: true}},
	}
}

const sampleHCL = `# nodr:managed vm/web
resource "example_vm" "web" {
  name    = "web"
  size    = 4096
  enabled = true
  tags    = ["a", "b"]

  cpu {
    cores = 2
    type  = "host"
  }

  disk {
    size    = 32
    storage = "local"
  }

  disk {
    size    = 64
    storage = "ceph"
    ssd     = true
  }
}
`

func TestRender(t *testing.T) {
	got, err := Render(target, "nodr:managed vm/web", sample())
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != sampleHCL {
		t.Errorf("Render =\n%s\nwant\n%s", got, sampleHCL)
	}
}

func TestLiftRenderedCode(t *testing.T) {
	got, states, err := Lift([]byte(sampleHCL), "vm.tf", target, testResource{})
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, sample()) {
		t.Errorf("Lift = %+v, want %+v", got, sample())
	}
	for _, s := range states {
		if s.Owner != lens.Synced {
			t.Errorf("%s is %s (%s), want synced", s.Path, s.Owner, s.Reason)
		}
	}
	lines := map[string]int{}
	for _, s := range states {
		lines[s.Path] = s.Line
	}
	for path, want := range map[string]int{"name": 3, "cpu.cores": 9, "disk[1].ssd": 21, "note": 0} {
		if lines[path] != want {
			t.Errorf("line of %s = %d, want %d", path, lines[path], want)
		}
	}
}

func TestLiftClassifiesOwnership(t *testing.T) {
	src := `resource "example_vm" "web" {
  name = "web-${var.suffix}"
  size = 2048 # nodr:keep
  note = upper("x")
  tags = null
  smbios_serial = "LIC-1"
  lifecycle {
    ignore_changes = [size]
  }
  dynamic "disk" {
    for_each = var.disks
    content {
      size    = disk.value
      storage = "local"
    }
  }
  cpu {
    cores = "four"
  }
  cpu {
    cores = 2
  }
}
`
	base := sample()
	got, states, err := Lift([]byte(src), "vm.tf", target, base)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"name":          "code-owned: set by an expression",
		"size":          "code-owned: pinned with nodr:keep",
		"enabled":       "synced",
		"note":          "code-owned: set by an expression",
		"tags":          "synced",
		"smbios_serial": "extension",
		"lifecycle":     "extension",
		"disk":          "code-owned: generated by a dynamic block",
		"disk.size":     "code-owned: generated by a dynamic block",
		"cpu":           "code-owned: the block is defined more than once",
		"cpu.cores":     "code-owned: the block is defined more than once",
		"agent":         "synced",
	}
	assertStates(t, states, want)
	if got.Name != base.Name || got.Size != base.Size || got.CPU.Cores != base.CPU.Cores {
		t.Errorf("code-owned fields must keep the base values, got %+v", got)
	}
	if got.Enabled != nil || got.Tags != nil {
		t.Errorf("absent and null optional attributes lift to zero values, got enabled=%v tags=%v", got.Enabled, got.Tags)
	}
	if len(got.Disks) != len(base.Disks) {
		t.Errorf("disks generated by a dynamic block keep the base values, got %d", len(got.Disks))
	}
}

