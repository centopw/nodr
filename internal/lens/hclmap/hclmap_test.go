func TestLiftMetaArguments(t *testing.T) {
	src := "resource \"example_vm\" \"web\" {\n  count = 2\n  name  = \"web\"\n}\n"
	got, states, err := Lift([]byte(src), "vm.tf", target, sample())
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, sample()) {
		t.Error("a resource with count must keep the base values")
	}
	for _, s := range states {
		if s.Owner != lens.CodeOwned || s.Reason != ReasonMetaArgument {
			t.Errorf("%s = %s (%s), want code-owned because of count", s.Path, s.Owner, s.Reason)
		}
	}
	out, err := Put([]byte(src), "vm.tf", target, testResource{Name: "other"})
	if err != nil || string(out) != src {
		t.Errorf("Put changed a resource with count: %v\n%s", err, out)
	}
}

func TestLiftErrors(t *testing.T) {
	if _, _, err := Lift([]byte("resource {"), "vm.tf", target, sample()); err == nil {
		t.Error("Lift of invalid HCL succeeded")
	}
	_, _, err := Lift([]byte(`resource "example_vm" "other" {}`), "vm.tf", target, sample())
	if !errors.Is(err, ErrTargetNotFound) {
		t.Errorf("Lift of a missing block: err = %v, want ErrTargetNotFound", err)
	}
}

func TestPutChangesOnlyWhatDiffers(t *testing.T) {
	src := `# nodr:managed vm/web
resource "example_vm" "web" {
  name    = "web" # the public name
  size    = 4096
  enabled = true
  tags    = ["b", "a"]
  extra   = "kept" # an extension

  cpu {
    cores = var.cores
    type  = "host"
  }

  disk {
    size    = 32
    storage = "local"
  }

  disk {
    size    = 64
    storage = "ceph"
    ssd     = true
  }
}
`
	desired := sample()
	desired.Size = 8192
	desired.CPU.Cores = 16
	out, err := Put([]byte(src), "vm.tf", target, desired)
	if err != nil {
		t.Fatal(err)
	}
	want := strings.Replace(src, "size    = 4096", "size    = 8192", 1)
	if string(out) != want {
		t.Errorf("Put =\n%s\nwant\n%s", out, want)
	}
}

