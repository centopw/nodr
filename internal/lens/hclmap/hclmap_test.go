func TestPutSpreadsSingleLineBlocks(t *testing.T) {
	src := "resource \"example_vm\" \"web\" {\n  name = \"web\"\n  size = 1\n\n  cpu { cores = 2 }\n\n  agent { enabled = true }\n}\n"
	tests := []struct {
		name    string
		desired testResource
		want    string
	}{
		{
			name:    "attribute",
			desired: testResource{Name: "web", Size: 1, CPU: &testCPU{Cores: 2, Type: "host"}, Agent: &testAgent{Enabled: true}},
			want:    "resource \"example_vm\" \"web\" {\n  name = \"web\"\n  size = 1\n\n  cpu {\n    cores = 2\n    type  = \"host\"\n  }\n\n  agent { enabled = true }\n}\n",
		},
		{
			name:    "value",
			desired: testResource{Name: "web", Size: 1, CPU: &testCPU{Cores: 8}, Agent: &testAgent{}},
			want:    "resource \"example_vm\" \"web\" {\n  name = \"web\"\n  size = 1\n\n  cpu { cores = 8 }\n\n  agent { enabled = false }\n}\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out, err := Put([]byte(src), "vm.tf", target, tt.desired)
			if err != nil {
				t.Fatal(err)
			}
			if string(out) != tt.want {
				t.Errorf("Put =\n%s\nwant\n%s", out, tt.want)
			}
		})
	}

	// An empty single-line block gets its first attribute, and a
	// single-line block that loses its only attribute stays.
	src = "resource \"example_vm\" \"web\" {\n  name=\"web\"\n  size=1\n  cpu {}\n  agent { enabled = true }\n}\n"
	type optionalAgent struct {
		Enabled *bool `hcl:"enabled,optional"`
	}
	desired := struct {
		Name  string         `hcl:"name"`
		Size  int            `hcl:"size"`
		CPU   *testCPU       `hcl:"cpu,block"`
		Agent *optionalAgent `hcl:"agent,block"`
	}{Name: "web", Size: 1, CPU: &testCPU{Type: "host"}, Agent: &optionalAgent{}}
	out, err := Put([]byte(src), "vm.tf", target, desired)
	if err != nil {
		t.Fatal(err)
	}
	want := "resource \"example_vm\" \"web\" {\n  name=\"web\"\n  size=1\n  cpu {\n    type = \"host\"\n  }\n  agent {  }\n}\n"
	if string(out) != want {
		t.Errorf("Put =\n%s\nwant\n%s", out, want)
	}
}

func TestPutInsertsAfterARemovedBlock(t *testing.T) {
	type item struct {
		N int `hcl:"n"`
	}
	type note struct {
		Text string `hcl:"text"`
	}
	type resource struct {
		Items []item `hcl:"item,block"`
		Note  *note  `hcl:"note,block,optional"`
	}
	// The blank line after the second item, which goes with it, holds
	// spaces.
	src := "resource \"example_vm\" \"web\" {\n  item {\n    n = 1\n  }\n  item {\n    n = 2\n  }\n      \n}\n"
	out, err := Put([]byte(src), "vm.tf", target, resource{Items: []item{{N: 1}}, Note: &note{Text: "x"}})
	if err != nil {
		t.Fatal(err)
	}
	want := "resource \"example_vm\" \"web\" {\n  item {\n    n = 1\n  }\n\n  note {\n    text = \"x\"\n  }\n}\n"
	if string(out) != want {
		t.Errorf("Put =\n%q\nwant\n%q", out, want)
	}
}

