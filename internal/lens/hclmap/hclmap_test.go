func TestSchemaErrors(t *testing.T) {
	type badOption struct {
		A string `hcl:"a,weird"`
	}
	type badType struct {
		A float64 `hcl:"a"`
	}
	type badBlock struct {
		A string `hcl:"a,block"`
	}
	type dupName struct {
		A string `hcl:"a"`
		B string `hcl:"a"`
	}
	for _, v := range []any{badOption{}, badType{}, badBlock{}, dupName{}, 3} {
		if _, err := schemaOf(reflect.TypeOf(v)); err == nil {
			t.Errorf("schemaOf(%T) succeeded", v)
		}
	}
}

func assertStates(t *testing.T, states []State, want map[string]string) {
	t.Helper()
	got := map[string]string{}
	for _, s := range states {
		desc := s.Owner.String()
		if s.Reason != "" {
			desc += ": " + s.Reason
		}
		got[s.Path] = desc
	}
	for path, w := range want {
		if got[path] != w {
			t.Errorf("%s = %q, want %q", path, got[path], w)
		}
	}
}

func TestPutWithKeep(t *testing.T) {
	desired := sample()
	desired.CPU.Type = "qemu64"
	desired.Disks = desired.Disks[:1]
	keep := map[string]bool{"cpu.type": true}
	out, err := PutWith([]byte(sampleHCL), "vm.tf", target, desired, Options{Keep: keep})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out), `type  = "host"`) || strings.Contains(string(out), "qemu64") {
		t.Errorf("a kept attribute was changed:\n%s", out)
	}
	if strings.Count(string(out), "disk {") != 1 {
		t.Errorf("the second disk was not removed:\n%s", out)
	}

	keep = map[string]bool{"disk[1].ssd": true}
	_, err = PutWith([]byte(sampleHCL), "vm.tf", target, desired, Options{Keep: keep})
	var conflict *ConflictError
	if !errors.As(err, &conflict) || conflict.Paths[0] != "disk[1]" {
		t.Errorf("removing a block with a kept attribute: err = %v, want a conflict", err)
	}
}

